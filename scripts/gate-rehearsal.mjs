// Deterministic isolated rehearsal. Never accepts real owner credentials or posts.
import { chromium } from "playwright";
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import assert from "node:assert/strict";
const home = process.env.DASH_REHEARSAL_DIR;
if (!home?.includes("rehearsal")) throw new Error("DASH_REHEARSAL_DIR must identify an isolated rehearsal");
const manifest = JSON.parse(readFileSync(resolve(home, "manifest.json"), "utf8"));
if (manifest.owner_decisions || manifest.live_posting || !manifest.credential_dir.includes("rehearsal") || !manifest.store.includes("rehearsal")) throw new Error("Refusing to automate real owner approvals");
const fixtureIds = JSON.parse(readFileSync(resolve(home, "fixture-ids.json"), "utf8"));
const records = () => {
  const rows = readFileSync(resolve(manifest.store, "events.jsonl"), "utf8").trim().split("\n").map(JSON.parse);
  return [...new Map(rows.map(i => [i.id, i])).values()];
};
const human = records().find(i => i.state === "pending" && i.policy.requires_human_text);
assert(human, "real copied pending human proposal required");
const screenshots = resolve(home, "screens"); mkdirSync(screenshots, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ["--disable-gpu"] });
const context = await browser.newContext({ viewport: { width: 412, height: 915 }, deviceScaleFactor: 1 });
const page = await context.newPage();
const errors = [];
page.on("pageerror", e => errors.push(e.message));
const shot = async name => { const path = resolve(screenshots,name+".png"); await page.screenshot({path}); return path; };
const result = { source_build: manifest.build_sha, viewport: "412x915", real_copied_items: records().length-fixtureIds.length, synthetic_fixture_items: fixtureIds.length, screenshots: [], checks: [], errors };
try {
  await page.goto(manifest.web_url, { waitUntil: "networkidle" });
  assert.equal(await page.evaluate(() => typeof window.__DASH_DEBUG__), "undefined");
  result.checks.push("production debug API absent");
  await page.getByPlaceholder("100.64.0.1", { exact: true }).fill(manifest.bridge_address);
  // This token is generated by the owned fixture bridge. Never use ~/.dash here.
  const bootstrap = readFileSync(resolve(manifest.credential_dir,"bootstrap-token"),"utf8").trim();
  await page.getByLabel("Bootstrap token",{exact:true}).fill(bootstrap);
  await page.getByText("Pair over Tailscale",{exact:true}).click();
  await page.getByRole("button",{name:"Approvals",exact:true}).waitFor({timeout:20000});
  result.checks.push("real authenticated Pair -> bridge hello -> Main");
  await page.getByRole("button",{name:"Approvals",exact:true}).click();
  await page.getByText("DRY RUN · Nothing will be posted",{exact:true}).waitFor();
  await page.getByText("Rehearsal decisions only. These are not live human approval.",{exact:true}).waitFor();
  result.screenshots.push(await shot("01-real-outbox-phone"));
  await page.getByRole("button",{name:"Select all bulk-safe",exact:true}).click();
  await page.getByRole("button",{name:"Approve selected (2)",exact:true}).click();
  result.screenshots.push(await shot("02-bulk-count-confirmation"));
  await page.getByRole("button",{name:"Confirm approve 2",exact:true}).click();
  await page.waitForFunction(() => document.body.textContent.includes("Approve selected (0)"));
  for(let n=0;n<100 && records().filter(i=>fixtureIds.slice(0,2).includes(i.id)&&i.state==="approved").length!==2;n++) await page.waitForTimeout(30);
  assert.equal(records().filter(i=>fixtureIds.slice(0,2).includes(i.id)&&i.state==="approved").length,2);
  result.checks.push("bulk approve exactly two synthetic rehearsal items; persisted readback; no canonical human receipt");
  const card = page.getByTestId(`gate-card-${human.id}`);
  await card.getByRole("button",{name:"Write response",exact:true}).click();
  const composer = page.getByLabel("Owner response",{exact:true});
  assert.equal(await composer.inputValue(),"");
  await composer.fill("REHEARSAL ONLY. Composer exercised on a copied real proposal. No real human approval or upstream posting.");
  result.screenshots.push(await shot("03-human-text-composer"));
  await page.getByRole("button",{name:"Save owner text",exact:true}).click();
  for(let n=0;n<100 && records().find(i=>i.id===human.id)?.state!=="edited";n++) await page.waitForTimeout(30);
  assert.equal(records().find(i=>i.id===human.id).state,"edited");
  assert.equal(records().find(i=>i.id===human.id).authorization,undefined);
  result.checks.push("human policy body initially blank; changed text required; edit persisted on copied real item only");
  await page.getByTestId(`gate-card-${fixtureIds[2]}`).getByRole("button",{name:"Reject",exact:true}).click();
  await page.getByLabel("Rejection reason",{exact:true}).fill("Rehearsal rejection. Synthetic item must never be posted.");
  result.screenshots.push(await shot("04-reject-reason"));
  await page.getByRole("button",{name:"Confirm reject",exact:true}).click();
  for(let n=0;n<100 && records().find(i=>i.id===fixtureIds[2])?.state!=="rejected";n++) await page.waitForTimeout(30);
  assert.equal(records().find(i=>i.id===fixtureIds[2]).state,"rejected");
  result.checks.push("reject requires reason; persisted readback");
  await page.reload({waitUntil:"networkidle"});
  await page.getByRole("button",{name:"Approvals",exact:true}).click();
  await page.getByText("DRY RUN · Nothing will be posted",{exact:true}).waitFor();
  result.checks.push("paired settings and outbox decisions survive reload");
  result.screenshots.push(await shot("05-reload-phone"));
  for(const [width,height] of [[800,1000],[1280,1000]]) { await page.setViewportSize({width,height}); result.screenshots.push(await shot(`06-width-${width}`)); }
  assert.equal(errors.length,0);
  result.passed=true;
} catch(e) {
  result.passed=false; result.failure=String(e); result.screenshots.push(await shot("failure")); throw e;
} finally {
  writeFileSync(resolve(home,"receipt.json"),JSON.stringify(result,null,2));
  await browser.close();
  console.log(JSON.stringify(result,null,2));
}
