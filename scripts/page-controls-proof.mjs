import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { spawn, execFileSync } from "node:child_process";
import { chromium } from "playwright";

const sha = process.env.D41_SOURCE_SHA;
assert.match(sha ?? "", /^[a-f0-9]{40}$/, "Supply exact committed D41_SOURCE_SHA");
const out = path.resolve("dist/d41");
await fs.mkdir(out, { recursive: true });
const built = await Bun.build({ entrypoints: ["app/src/debug/page-controls-fixture.tsx"], target: "browser", minify: false });
assert(built.success, built.logs.map(String).join("\n"));
const bundle = await built.outputs[0].text();
const html = `<!doctype html><html><head><meta charset="utf-8"><title>D41 registry fixture</title><style>body{background:#080808;color:#eee;font:16px system-ui;margin:24px;max-width:680px}h1{font-size:24px}button,select{background:#202020;color:#eee;border:1px solid #666;border-radius:8px;padding:10px;margin:4px}button[aria-pressed=true]{border-color:#ddb86e;color:#ddb86e}.mounted{display:flex;gap:12px;font-size:12px;color:#aaa}pre{white-space:pre-wrap;font-size:12px}.row{border-top:1px solid #333;padding:8px}.row label{display:flex;justify-content:space-between;align-items:center}</style></head><body><div id="root"></div><script type="module" src="/fixture.js"></script></body></html>`;
await fs.writeFile(path.join(out, "fixture.html"), html);
await fs.writeFile(path.join(out, "fixture.js"), bundle);
const server = Bun.serve({ hostname: "127.0.0.1", port: 0, fetch(request) { return new Response(new URL(request.url).pathname === "/fixture.js" ? bundle : html, { headers: { "Content-Type": new URL(request.url).pathname === "/fixture.js" ? "text/javascript" : "text/html" } }); } });
const runtime = await fs.mkdtemp(path.join(os.tmpdir(), "d41-sway-"));
await fs.chmod(runtime, 0o700);
const env = { ...process.env };
for (const name of ["DISPLAY", "WAYLAND_DISPLAY", "SWAYSOCK", "HYPRLAND_INSTANCE_SIGNATURE", "WAYLAND_SOCKET", "DBUS_SESSION_BUS_ADDRESS"]) delete env[name];
Object.assign(env, { XDG_RUNTIME_DIR: runtime, XDG_CACHE_HOME: path.join(runtime, "cache"), WLR_BACKENDS: "headless", WLR_RENDERER: "pixman", WLR_LIBINPUT_NO_DEVICES: "1" });
const config = path.join(runtime, "sway.conf");
await fs.writeFile(config, "xwayland disable\noutput HEADLESS-1 mode 1000x1100\nseat seat0 xcursor_theme Adwaita 24\n");
let swayLog = "";
const sway = spawn("/usr/bin/sway", ["-c", config], { env, stdio: ["ignore", "pipe", "pipe"] });
sway.stdout.on("data", data => swayLog += data); sway.stderr.on("data", data => swayLog += data);
let browser;
const checks = [];
const errors = [];
try {
  let socket;
  for (let attempt = 0; attempt < 100; attempt++) {
    if (sway.exitCode !== null) throw new Error(`Owned Sway exited ${sway.exitCode}: ${swayLog}`);
    socket = (await fs.readdir(runtime)).find(name => name.includes(`.${sway.pid}.sock`) && name.startsWith("sway-ipc."));
    if (socket) break;
    await new Promise(resolve => setTimeout(resolve, 50));
  }
  assert(socket, `No owned Sway IPC socket: ${swayLog}`);
  const ipc = path.join(runtime, socket);
  const outputs = JSON.parse(execFileSync("swaymsg", ["-s", ipc, "-t", "get_outputs", "-r"], { env, encoding: "utf8" }));
  assert(outputs.length === 1 && outputs[0].name === "HEADLESS-1", "Only owned headless output is allowed");
  const display = (await fs.readdir(runtime)).find(name => /^wayland-\d+$/.test(name));
  assert(display, "Missing owned Wayland socket");
  const browserEnv = { ...env, WAYLAND_DISPLAY: display, SWAYSOCK: ipc };
  browser = await chromium.launch({ headless: false, args: ["--ozone-platform=wayland"], env: browserEnv });
  const page = await browser.newPage({ viewport: { width: 720, height: 1000 } });
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(server.url.href);
  const rows = page.getByTestId("registry-rows");
  const rowIds = () => rows.locator(".row").evaluateAll(elements => elements.map(el => el.getAttribute("data-testid")));
  await page.getByTestId("chats-action").waitFor();
  for (const name of ["bots", "chats", "orchestra"]) assert.equal(await page.getByTestId(`mounted-${name}`).count(), 1);
  assert.deepEqual(await rowIds(), ["chats-action"]);
  await page.getByRole("button", { name: "Fresh callback", exact: true }).click();
  await rows.getByRole("button", { name: "Run", exact: true }).click();
  assert.equal(await page.getByTestId("dispatch").innerText(), "chats:1");
  await page.getByRole("button", { name: "bots", exact: true }).click();
  assert.deepEqual(await rowIds(), ["bots-action"]);
  await page.getByRole("button", { name: "orchestra", exact: true }).click();
  const initial = ["orchestra-view", "orchestra-focus", "orchestra-filter", "orchestra-selection", "orchestra-reset"];
  assert.deepEqual(await rowIds(), initial);
  checks.push("all panes remain mounted; only active page rows; latest callback");
  await page.getByRole("combobox", { name: "Selection", exact: true }).selectOption("2");
  await page.getByRole("combobox", { name: "Scope", exact: true }).selectOption("1");
  await page.getByRole("combobox", { name: "Highlight", exact: true }).selectOption("1");
  await page.getByRole("combobox", { name: "Filter", exact: true }).selectOption("1");
  const state = async () => JSON.parse(await page.getByTestId("orchestra-state").innerText());
  assert.deepEqual((await state()).filter, { kind: "chat", only: true });
  assert.equal((await state()).focusId, "chat"); assert.equal((await state()).focusOnly, false);
  await page.screenshot({ path: path.join(out, "orchestra-focused.png") });
  await page.getByRole("combobox", { name: "View", exact: true }).selectOption("2");
  assert.deepEqual(await state(), { view: "work", chosen: true, filter: null, focusId: null, focusOnly: false, viewRevision: 1 });
  assert.deepEqual(await rowIds(), initial);
  await page.getByRole("combobox", { name: "Selection", exact: true }).selectOption("2");
  await page.getByRole("combobox", { name: "Highlight", exact: true }).selectOption("3");
  await page.getByTestId("orchestra-reset").getByRole("button").click();
  assert.deepEqual(await state(), { view: "work", chosen: true, filter: null, focusId: null, focusOnly: false, viewRevision: 1 });
  checks.push("real controller selection, scope, only, switch reset and reset action");
  await page.getByRole("button", { name: "Blur route", exact: true }).click();
  assert.deepEqual(await rowIds(), []);
  await page.screenshot({ path: path.join(out, "route-blurred.png") });
  await page.getByRole("button", { name: "Fresh callback", exact: true }).click();
  await page.getByRole("button", { name: "Refocus route", exact: true }).click();
  assert.deepEqual(await rowIds(), initial);
  await page.screenshot({ path: path.join(out, "route-refocused.png") });
  await page.getByRole("button", { name: "chats", exact: true }).click();
  await rows.getByRole("button", { name: "Run", exact: true }).click();
  assert.equal(await page.getByTestId("dispatch").innerText(), "chats:2");
  assert.deepEqual(await rowIds(), ["chats-action"]);
  checks.push("route blur removes rows immediately; refocus has no duplicates and fresh callbacks (React StrictMode)");
  assert.deepEqual(errors, []);
  await fs.writeFile(path.join(out, "results.json"), JSON.stringify({ sourceSHA: sha, fixtureOnly: true, swayPid: sway.pid, ipc, display, output: outputs[0].name, checks, errors }, null, 2));
  console.log(JSON.stringify({ sourceSHA: sha, checks, out }));
} finally {
  await browser?.close();
  server.stop(true);
  sway.kill("SIGTERM");
  await fs.writeFile(path.join(out, "sway.log"), swayLog);
  await fs.rm(runtime, { recursive: true, force: true });
}
