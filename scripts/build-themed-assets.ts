// Regenerates the themed-mode modules the native app needs (no network, no new dependency):
//   app/src/vendor/blueprint-wallpaper/player.generated.ts  the WebView page script (bundled mount + player)
//   app/src/vendor/blueprint-wallpaper/assets.generated.ts  plate and maps as data URIs (native WebView)
//   app/src/components/themed/elemental-textures.generated.ts  elemental-ui basecolor maps as data URIs
// Usage: bun scripts/build-themed-assets.ts [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const app = join(root, "app");
const check = process.argv.includes("--check");
const banner = "// GENERATED by scripts/build-themed-assets.ts. Do not edit.\n";
const outputs: [string, string][] = [];

const bundle = await Bun.build({ entrypoints: [join(app, "src/vendor/blueprint-wallpaper/webview-entry.ts")], target: "browser", minify: true, format: "iife" });
if (!bundle.success) { for (const log of bundle.logs) console.error(log); process.exit(1); }
const first = bundle.outputs[0];
if (!first) { console.error("build-themed-assets: no bundle output"); process.exit(1); }
const js = await first.text();
outputs.push(["src/vendor/blueprint-wallpaper/player.generated.ts",
  `${banner}// Bundle of webview-entry.ts (blueprint Living Ruins player, GPL-3.0-only; see README.md).\nexport const WALLPAPER_PLAYER_JS = ${JSON.stringify(js)};\n`]);

const uri = (file: string, mime: string) => `data:${mime};base64,${readFileSync(join(app, file)).toString("base64")}`;
const plate = (name: string) => uri(`public/wallpaper/living-ruins/${name}.webp`, "image/webp");
outputs.push(["src/vendor/blueprint-wallpaper/assets.generated.ts",
  `${banner}// blueprint Living Ruins runtime plate and maps (app/public/wallpaper/living-ruins), for the native WebView.\n` +
  `export const NATIVE_WALLPAPER_ASSETS = {\n${["base", "masks", "flow", "depth"].map(n => `  ${n}: ${JSON.stringify(plate(n))},`).join("\n")}\n};\n`]);

const materials = ["geo.basalt.vesicular.v1", "geo.slate.layered.v1", "geo.limestone.porous.v1"];
outputs.push(["src/components/themed/elemental-textures.generated.ts",
  `${banner}// elemental-ui basecolor maps (app/assets/elemental, from \`tools/elemental.py generate --size 256\`; GPL-3.0-only).\n` +
  `export const ELEMENTAL_TEXTURES: Record<string, string> = {\n${materials.map(m => `  ${JSON.stringify(m)}: ${JSON.stringify(uri(`assets/elemental/${m}.png`, "image/png"))},`).join("\n")}\n};\n`]);

let stale = 0;
for (const [file, text] of outputs) {
  const path = join(app, file);
  let current = "";
  try { current = readFileSync(path, "utf8"); } catch { current = ""; }
  if (current === text) continue;
  if (check) { console.error(`stale: app/${file}`); stale++; continue; }
  writeFileSync(path, text);
  console.log(`wrote app/${file} (${text.length} bytes)`);
}
if (stale) process.exit(1);
