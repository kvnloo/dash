// Synthetic stand-in for the kit's trace and intent fixtures. The kit ships sanitized real measurements;
// Dash is public, so it vendors only their shape. Every value is replaced, deterministically:
//   numbers  -> independent random factor 0.4-1.6 (ids, versions and 0/1 flags keep their value)
//   times    -> one whole-day shift for the document; span ends keep start <= end with a random length
//   text     -> neutral filler words (same string in, same filler out, so grouping still works)
//   hashes   -> random hex of the same length
const WORDS = ("amber basil cedar delta ember fern grove harbor iris juniper kelp lumen maple nectar onyx pebble quartz "
  + "river sage tidal umber vale willow yarrow zephyr build check draft merge plan queue retry sample sketch stage test trace").split(" ");
const KEEP = /^(id|entryId|v|spec|revision|version|schema|\$schema|protocol|topology|kind|type|role|stopReason|harness|status|app)$/;

function rng(seed) {
  let a = 0; for (const c of seed) a = (Math.imul(a ^ c.charCodeAt(0), 2654435761) >>> 0);
  return () => { a = (a + 0x6d2b79f5) >>> 0; let t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}

export function synthesize(name, doc) {
  const r = rng(`dash-eui-synthetic-v1:${name}`);
  const shift = -Math.round(20 + r() * 60) * 86_400_000;
  const memo = new Map();
  const filler = (s) => {
    if (!memo.has(s)) {
      const n = Math.max(2, Math.round(s.split(/\s+/).length * (0.7 + r() * 0.6)));
      const words = Array.from({ length: n }, () => WORDS[Math.floor(r() * WORDS.length)]);
      memo.set(s, words.join(" ").replace(/^./, (c) => c.toUpperCase()));
    }
    return memo.get(s);
  };
  const hex = (s) => { if (!memo.has(s)) memo.set(s, Array.from(s, () => "0123456789abcdef"[Math.floor(r() * 16)]).join("")); return memo.get(s); };
  const isTime = (v) => v > 1e12 && v < 4e12;
  const num = (v, key) => {
    if (KEEP.test(key) || Number.isInteger(v) && v >= 0 && v <= 1) return v;
    if (isTime(v)) return v + shift;
    const f = 0.4 + r() * 1.2;
    if (Number.isInteger(v)) return Math.round(v * f);
    return v > 0 && v <= 1 ? Math.min(1, v * f) : v * f;
  };
  const str = (s, key) => {
    if (KEEP.test(key)) return s;
    if (/^[0-9a-f]{16,}$/.test(s)) return hex(s);
    if (/^\d{4}-\d\d-\d\dT/.test(s)) { const t = Date.parse(s); return Number.isNaN(t) ? s : new Date(t + shift).toISOString().replace(/:\d\d\.\d{3}Z$/, "Z"); }
    if (/\s/.test(s.trim()) && s.length > 16 || /^[~/]/.test(s) && s.length > 2) return filler(s);
    // Work references (owner/repo#123, branch names) become sample references.
    if (/^[\w.-]+\/[\w.-]+#\d+$/.test(s) || /^(feat|fix|chore|docs|lane|integ)\//.test(s)) {
      if (!memo.has(s)) memo.set(s, s.includes("#") ? `sample/repo#${100 + Math.floor(r() * 900)}` : `feat/${WORDS[Math.floor(r() * WORDS.length)]}-${WORDS[Math.floor(r() * WORDS.length)]}`);
      return memo.get(s);
    }
    return s;
  };
  const walk = (x, key = "") => {
    if (Array.isArray(x)) return x.map((v) => walk(v, key));
    if (x && typeof x === "object") {
      const out = {};
      for (const [k, v] of Object.entries(x)) out[k] = walk(v, k);
      // Spans: keep a valid interval with a random (not measured) length.
      if (typeof x.start === "number" && typeof x.end === "number" && isTime(x.start)) out.end = out.start + Math.round((x.end - x.start) * (0.4 + r() * 1.2));
      return out;
    }
    if (typeof x === "number") return num(x, key);
    if (typeof x === "string") return str(x, key);
    return x;
  };
  const out = walk(doc);
  if (typeof out.source === "string" || name === "trace") out.source = "synthetic: generated by app/scripts/ephemeral-kit/synthetic.mjs (shape of the kit fixture, random values)";
  return out;
}
